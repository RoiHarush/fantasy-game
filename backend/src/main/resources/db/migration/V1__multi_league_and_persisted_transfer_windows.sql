ALTER TABLE leagues
    ADD COLUMN IF NOT EXISTS max_participants INTEGER NOT NULL DEFAULT 8;

CREATE UNIQUE INDEX IF NOT EXISTS uk_leagues_league_code
    ON leagues (league_code);

CREATE TABLE IF NOT EXISTS league_scoring_rules (
    league_id BIGINT NOT NULL REFERENCES leagues(id) ON DELETE CASCADE,
    rule_key VARCHAR(80) NOT NULL,
    points INTEGER NOT NULL,
    PRIMARY KEY (league_id, rule_key)
);

ALTER TABLE user_game_data
    ADD COLUMN IF NOT EXISTS league_id BIGINT;

UPDATE user_game_data AS game_data
SET league_id = (
    SELECT MIN(membership.league_id)
    FROM league_users AS membership
    WHERE membership.user_id = game_data.user_id
)
WHERE game_data.league_id IS NULL;

CREATE INDEX IF NOT EXISTS ix_user_game_data_league
    ON user_game_data (league_id);

