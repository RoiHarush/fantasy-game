CREATE TABLE IF NOT EXISTS league_transfer_windows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id BIGINT NOT NULL REFERENCES leagues(id) ON DELETE CASCADE,
    gameweek_id INTEGER NOT NULL REFERENCES gameweeks(id) ON DELETE CASCADE,
    window_type VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    phase VARCHAR(16) NOT NULL,
    regular_cursor INTEGER NOT NULL DEFAULT 0,
    ir_cursor INTEGER NOT NULL DEFAULT 0,
    opened_at TIMESTAMP,
    closed_at TIMESTAMP,
    turn_started_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_transfer_window_league_gw_type
        UNIQUE (league_id, gameweek_id, window_type)
);

CREATE INDEX IF NOT EXISTS ix_transfer_window_league_status
    ON league_transfer_windows (league_id, status);

CREATE TABLE IF NOT EXISTS league_transfer_window_order (
    window_id BIGINT NOT NULL REFERENCES league_transfer_windows(id) ON DELETE CASCADE,
    turn_position INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    PRIMARY KEY (window_id, turn_position)
);

CREATE TABLE IF NOT EXISTS league_transfer_window_ir_order (
    window_id BIGINT NOT NULL REFERENCES league_transfer_windows(id) ON DELETE CASCADE,
    turn_position INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    PRIMARY KEY (window_id, turn_position)
);

CREATE TABLE IF NOT EXISTS league_draft_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id BIGINT NOT NULL UNIQUE REFERENCES leagues(id) ON DELETE CASCADE,
    scheduled_time TIMESTAMP,
    processed BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS waiver_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id BIGINT NOT NULL REFERENCES leagues(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    gameweek_id INTEGER NOT NULL REFERENCES gameweeks(id) ON DELETE CASCADE,
    priority INTEGER NOT NULL,
    player_in_id INTEGER NOT NULL REFERENCES players(id),
    player_out_id INTEGER NOT NULL REFERENCES players(id),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_waiver_user_gw_priority
        UNIQUE (league_id, user_id, gameweek_id, priority)
);

CREATE INDEX IF NOT EXISTS ix_waiver_lookup
    ON waiver_preferences (league_id, user_id, gameweek_id, priority);

UPDATE players
SET owner_id = -1,
    state = 'NONE'
WHERE state IS NULL OR state <> 'LOCKED';
